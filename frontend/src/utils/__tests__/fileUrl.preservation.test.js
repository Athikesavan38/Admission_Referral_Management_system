/**
 * Preservation Property Tests — Property 2: Null/Empty Path Fallback Behavior
 *
 * **Validates: Requirements 3.1, 3.2**
 *
 * EXPECTED OUTCOME: Tests PASS (confirms no regressions — null guards are preserved).
 * These tests confirm the baseline null-guard behavior is preserved after the fix.
 *
 * After the fix:
 *   - getFileUrl(null), getFileUrl(undefined), getFileUrl("") all return null,
 *     so the existing null guard (r.photo ? <img> : <div gradient>) continues
 *     to render the fallback gradient avatar — NOT a broken <img> element.
 *   - When r.documents is [] or absent, the documents section is hidden entirely.
 *
 * Property to assert (null/empty inputs):
 *   For all values generated by fc.oneof(fc.constant(null), fc.constant(undefined),
 *   fc.constant("")), getFileUrl returns null — the <img> branch is never entered.
 */

import { describe, it, beforeEach } from 'vitest';
import { expect, vi } from 'vitest';
import fc from 'fast-check';
import { getFileUrl } from '../fileUrl.js';

// ---------------------------------------------------------------------------
// Documents visibility helper — mirrors the guard in ReferralStatus.jsx
// ---------------------------------------------------------------------------

/**
 * Mirrors the documents section guard in ReferralStatus.jsx / AdminDetailCard:
 *   r.documents?.length > 0 ? <documents section> : null
 *
 * Returns true if the documents section would be shown, false if hidden.
 */
function documentsVisible(documents) {
  return documents != null && documents.length > 0;
}

// ---------------------------------------------------------------------------
// Property 2: Preservation — Null/Empty Path Fallback Behavior
// ---------------------------------------------------------------------------
describe('Property 2: Preservation — Null/Empty Path Fallback Behavior', () => {
  beforeEach(() => {
    // Use an absolute base URL so getFileUrl exercises the origin-extraction path
    vi.stubEnv('VITE_API_BASE_URL', 'http://localhost:5000/api');
  });

  // Arbitrary: null, undefined, or empty string — the three falsy photo values
  const nullishPathArb = fc.oneof(
    fc.constant(null),
    fc.constant(undefined),
    fc.constant('')
  );

  it(
    'getFileUrl returns null for null/undefined/"" — img branch is never entered',
    () => {
      fc.assert(
        fc.property(nullishPathArb, (path) => {
          const result = getFileUrl(path);
          // getFileUrl must return null so the fallback avatar renders
          // and the <img> branch is never entered
          expect(result).toBeNull();
          return result === null; // explicit boolean return for fast-check
        })
      );
    }
  );

  it(
    'getFileUrl never passes null/undefined/"" through to an img src — fallback avatar is always shown',
    () => {
      fc.assert(
        fc.property(nullishPathArb, (path) => {
          const imgSrc = getFileUrl(path);
          // imgSrc must be null — no <img> element would be rendered
          return imgSrc === null;
        })
      );
    }
  );

  it(
    'empty documents array causes documents section to be hidden',
    () => {
      // Empty array — documents section must be hidden
      expect(documentsVisible([])).toBe(false);
    }
  );

  it(
    'absent (null/undefined) documents causes documents section to be hidden',
    () => {
      fc.assert(
        fc.property(
          fc.oneof(fc.constant(null), fc.constant(undefined)),
          (docs) => {
            return documentsVisible(docs) === false;
          }
        )
      );
    }
  );

  it(
    'non-empty documents array causes documents section to be shown',
    () => {
      fc.assert(
        fc.property(
          fc.array(fc.string({ minLength: 1 }), { minLength: 1, maxLength: 10 }),
          (docs) => {
            return documentsVisible(docs) === true;
          }
        )
      );
    }
  );
});
